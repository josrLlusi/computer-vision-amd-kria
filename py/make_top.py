"""Generate a fixed-parameter top (rtl/yolo26_head_kria_top.v) sized from a generated test's meta.json.
usage: python make_top.py META.json [--lanes 16] [--K 300] [--yxw 10] [--cw 10] [--out rtl/yolo26_head_kria_top.v]
Budget knobs: --K (max detections kept; COCO evaluates at most 100 per image), --yxw/--cw (sorter payload widths),
--lanes (MAC lanes). See README 'Footprint'."""
import argparse, json, math
ap = argparse.ArgumentParser()
ap.add_argument('meta'); ap.add_argument('--lanes', type=int, default=16); ap.add_argument('--K', type=int, default=300)
ap.add_argument('--yxw', type=int, default=10); ap.add_argument('--cw', type=int, default=10)
ap.add_argument('--out', default='rtl/yolo26_head_kria_top.v'); ap.add_argument('--name', default='yolo26_head_kria_top')
a = ap.parse_args()
lg = lambda n, lo: max(lo, math.ceil(math.log2(n + 1)))
m = json.load(open(a.meta)); L = a.lanes
assert m['nc'] <= 2 ** a.cw, 'nc does not fit in CW bits'
assert max(max(s[2], s[3]) for s in m['scales']) <= 2 ** a.yxw, 'grid does not fit in YXW bits'
p = dict(LANES=L, LOGL=int(math.log2(L)), AAW=lg(m['act_words'], 6), WAW=lg(m['n_wgt'], 6), PAW=lg(m['n_par'], 6),
         LAW=lg(m['n_lut'] + 256, 8), PRW=lg(m['n_prog'], 6), BAW=lg(m['box_words'], 6), K=a.K, IW=lg(a.K, 4),
         OUTAW=lg(6 * a.K + 6, 8), YXW=a.yxw, CW=a.cw,
         D_PROG=m['n_prog'], D_PAR=m['n_par'], D_WGT=m['n_wgt'], D_LUT=m['n_lut'] + 256, D_ACT=m['act_words'], D_BOX=m['box_words'])
ports = """    input  wire        aclk,
    input  wire        aresetn,
    input  wire [23:0] s_axi_awaddr,  input  wire s_axi_awvalid, output wire s_axi_awready,
    input  wire [31:0] s_axi_wdata,   input  wire [3:0] s_axi_wstrb, input wire s_axi_wvalid, output wire s_axi_wready,
    output wire [1:0]  s_axi_bresp,   output wire s_axi_bvalid,  input  wire s_axi_bready,
    input  wire [23:0] s_axi_araddr,  input  wire s_axi_arvalid, output wire s_axi_arready,
    output wire [31:0] s_axi_rdata,   output wire [1:0] s_axi_rresp, output wire s_axi_rvalid, input wire s_axi_rready,
    output wire        irq"""
names = ['aclk','aresetn','s_axi_awaddr','s_axi_awvalid','s_axi_awready','s_axi_wdata','s_axi_wstrb','s_axi_wvalid','s_axi_wready',
         's_axi_bresp','s_axi_bvalid','s_axi_bready','s_axi_araddr','s_axi_arvalid','s_axi_arready','s_axi_rdata','s_axi_rresp',
         's_axi_rvalid','s_axi_rready','irq']
conn = ',\n        '.join(f'.{n}({n})' for n in names)
open(a.out, 'w').write(f"""`timescale 1ns/1ps
// AUTO-GENERATED by py/make_top.py from {a.meta}: fixed-parameter top for block design / synthesis.
//   {p}
module {a.name} (
{ports}
);
    yolo26_head_axil #({', '.join(f'.{k}({v})' for k, v in p.items())}) u_head (
        {conn});
endmodule
""")
print(p)
